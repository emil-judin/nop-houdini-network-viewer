import type { OperatorIconDef } from '../iconTypes';
import { SOP_ICON_DOMAINS, type SopIconDomain } from './domains';

/**
 * Lookup keys of one domain's drawings. Lists are single strings of space-separated words: the
 * index ships with every viewer, and strings are its smallest form.
 */
export interface SopIconDomainKeys {
  /** Lowercased operator base types (`OperatorIconDef.types`). */
  types: string;
  /** Lowercased extra Houdini icon ids (`OperatorIconDef.icons`). */
  icons: string;
  /** Drawing ids without the `sop.` prefix, for Labs aliases and the subnetwork icon. */
  ids: string;
  /** `true` when a drawing of the domain has a custom matcher (`OperatorIconDef.matches`). */
  matchers: boolean;
}

/** Which domain holds which drawing: the data of `iconIndex.generated.ts`. */
export type SopIconIndex = Record<SopIconDomain, SopIconDomainKeys>;

const SOP_ID_PREFIX = 'sop.';

/** Unique words in first-seen order, joined with spaces. */
function joinWords(words: Iterable<string>): string {
  return [...new Set(words)].join(' ');
}

/**
 * Maps a built-in icon id such as `sop_copytopoints-2.0` to its operator name (`copytopoints`).
 */
export function sopIconToType(baseIcon: string): string | null {
  const match = /^sop_(.+?)(?:-\d+(?:\.\d+)*)?$/.exec(baseIcon);
  return match ? match[1] : null;
}

/**
 * Builds the icon index from the drawings of every domain. Not used by the viewer at run time:
 * `npm run icons:index` writes its result to `iconIndex.generated.ts`, and a unit test checks that
 * the committed file is current.
 *
 * Keys the lookup finds anyway are left out: an icon id `sop_<type>` whose type belongs to the same
 * drawing, and a drawing id `sop.<type>` of the drawing that owns that type.
 */
export function buildSopIconIndex(byDomain: Record<SopIconDomain, readonly OperatorIconDef[]>): SopIconIndex {
  // The drawing that wins each key, as in the lookup: later domains and later drawings win
  const typeOwner = new Map<string, OperatorIconDef>();
  const iconOwner = new Map<string, OperatorIconDef>();
  for (const domain of SOP_ICON_DOMAINS) {
    for (const def of byDomain[domain]) {
      if (!def.id.startsWith(SOP_ID_PREFIX)) throw new Error(`SOP icon id must start with "sop.": ${def.id}`);
      for (const word of [...def.types, ...(def.icons ?? [])]) {
        if (/\s/.test(word)) throw new Error(`Icon key with a space in ${def.id}: "${word}"`);
      }
      for (const t of def.types) typeOwner.set(t.toLowerCase(), def);
      for (const icon of def.icons ?? []) iconOwner.set(icon.toLowerCase(), def);
    }
  }
  const isImpliedIcon = (icon: string, def: OperatorIconDef) => {
    const type = sopIconToType(icon);
    return type !== null && typeOwner.get(type) === def;
  };
  const isImpliedId = (def: OperatorIconDef) => typeOwner.get(def.id.slice(SOP_ID_PREFIX.length)) === def;

  const index = {} as SopIconIndex;
  for (const domain of SOP_ICON_DOMAINS) {
    const defs = byDomain[domain];
    index[domain] = {
      types: joinWords(defs.flatMap((def) => def.types.map((t) => t.toLowerCase()))),
      icons: joinWords(
        defs.flatMap((def) =>
          (def.icons ?? [])
            .map((icon) => icon.toLowerCase())
            .filter((icon) => iconOwner.get(icon) === def && !isImpliedIcon(icon, def)),
        ),
      ),
      ids: joinWords(defs.filter((def) => !isImpliedId(def)).map((def) => def.id.slice(SOP_ID_PREFIX.length))),
      matchers: defs.some((def) => def.matches !== undefined),
    };
  }
  return index;
}

/** The source text of `iconIndex.generated.ts` for an index (formatted by Prettier afterwards). */
export function renderSopIconIndexModule(index: SopIconIndex): string {
  return [
    '// Generated by `npm run icons:index` from the drawings in the domain folders. Do not edit by hand:',
    '// change the drawings, then run the script again (a unit test fails while this file is out of date).',
    '',
    "import type { SopIconIndex } from './iconIndexBuilder';",
    '',
    '/** Which SOP icon domain holds which operator type, icon id and drawing id. */',
    `export const SOP_ICON_INDEX: SopIconIndex = ${JSON.stringify(index, null, 2)};`,
    '',
  ].join('\n');
}
