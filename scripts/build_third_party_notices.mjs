/**
 * Writes THIRD_PARTY_NOTICES.md: the licenses of the third-party code and fonts that NOP's builds
 * ship (the web component bundle, the npm package's fonts and the playground site).
 *
 * Run after `npm run build:lib`: the bundled packages are read from the source maps in `dist/`, so
 * the list always matches what was really bundled. Fonts are read from the stylesheets that load
 * them. Each license text is copied word for word from the installed package.
 *
 *   node scripts/build_third_party_notices.mjs           writes the file
 *   node scripts/build_third_party_notices.mjs --check   fails if the file is out of date
 */
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const OUT = join(ROOT, 'THIRD_PARTY_NOTICES.md');

/** Stylesheets that load fonts, and where each one ships. */
const FONT_SHEETS = [
  { file: 'src/styles/fonts.css', shipsIn: 'npm package, web component, playground' },
  { file: 'src/playground/index.css', shipsIn: 'playground only (NOP banner)' },
];

/**
 * Copyright lines of the fonts, from the font files' own `name` table. The fontsource LICENSE
 * files only say "Google Inc.", which is not the copyright holder of the Source fonts.
 */
const FONT_COPYRIGHTS = {
  'source-sans-pro': {
    name: 'Source Sans Pro',
    copyright:
      'Copyright 2010-2018 Adobe Systems Incorporated (http://www.adobe.com/), with Reserved Font Name "Source".',
  },
  'source-code-pro': {
    name: 'Source Code Pro',
    copyright: 'Copyright 2023 Adobe (http://www.adobe.com/), with Reserved Font Name "Source".',
  },
  'noto-sans': {
    name: 'Noto Sans',
    copyright: 'Copyright 2022 The Noto Project Authors (https://github.com/notofonts/latin-greek-cyrillic)',
  },
};

const LICENSE_FILES = ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'license', 'license.md', 'LICENCE'];

function packageJson(name) {
  return JSON.parse(readFileSync(join(ROOT, 'node_modules', name, 'package.json'), 'utf8'));
}

function licenseText(name) {
  for (const file of LICENSE_FILES) {
    const path = join(ROOT, 'node_modules', name, file);
    if (existsSync(path)) return readFileSync(path, 'utf8').replace(/\r\n/g, '\n').trim();
  }
  throw new Error(`No license file found for ${name}`);
}

/** Every package that appears in a source map under `dist/`. */
function bundledPackages() {
  const dist = join(ROOT, 'dist');
  if (!existsSync(join(dist, 'web-component.js.map'))) {
    throw new Error('dist/web-component.js.map not found: run `npm run build:lib` first.');
  }
  const names = new Set();
  const walk = (dir) => {
    for (const entry of readdirSync(dir)) {
      const path = join(dir, entry);
      if (statSync(path).isDirectory()) walk(path);
      else if (path.endsWith('.map')) {
        for (const source of JSON.parse(readFileSync(path, 'utf8')).sources) {
          const match = source.match(/node_modules\/((?:@[^/]+\/)?[^/]+)/);
          if (match) names.add(match[1]);
        }
      }
    }
  };
  walk(dist);
  return [...names].sort();
}

/** Fontsource packages loaded by the stylesheets, with where each ships. */
function fonts() {
  const found = new Map();
  for (const sheet of FONT_SHEETS) {
    const css = readFileSync(join(ROOT, sheet.file), 'utf8');
    for (const match of css.matchAll(/@fontsource\/([a-z0-9-]+)\/files\/[a-z0-9-]+-(\d{3})-normal\.woff2/g)) {
      const [, pkg, weight] = match;
      if (!found.has(pkg)) found.set(pkg, { pkg, weights: new Set(), shipsIn: sheet.shipsIn });
      found.get(pkg).weights.add(weight);
    }
  }
  return [...found.values()];
}

/** The SIL Open Font License text without the font-specific copyright header above it. */
function oflText(pkg) {
  const text = licenseText(`@fontsource/${pkg}`);
  const start = text.indexOf('SIL OPEN FONT LICENSE');
  if (start < 0) throw new Error(`@fontsource/${pkg}: license is not the SIL Open Font License`);
  return text.slice(start).trim();
}

function render() {
  const fontList = fonts();
  const packages = bundledPackages();
  const lines = [
    '# Third-party notices',
    '',
    'NOP is MIT licensed ([`LICENSE`](./LICENSE)). The web component (`dist/web-component.js`) and the playground include the fonts and libraries below, under their own licenses.',
    '',
    'Generated by `scripts/build_third_party_notices.mjs`. Do not edit by hand.',
    '',
    '## Fonts',
    '',
    '| Font | Weights | Ships in | License |',
    '| --- | --- | --- | --- |',
  ];
  for (const font of fontList) {
    const meta = FONT_COPYRIGHTS[font.pkg];
    if (!meta) throw new Error(`Add the copyright line of @fontsource/${font.pkg} to FONT_COPYRIGHTS`);
    lines.push(
      `| ${meta.name} | ${[...font.weights].sort().join(', ')} | ${font.shipsIn} | SIL Open Font License 1.1 |`,
    );
  }
  lines.push(
    '',
    '## Libraries bundled in the web component and the playground',
    '',
    '| Package | Version | License |',
    '| --- | --- | --- |',
  );
  for (const name of packages) {
    const json = packageJson(name);
    lines.push(`| ${name} | ${json.version} | ${json.license} |`);
  }
  lines.push('', '## License texts', '', '### Fonts', '');
  for (const font of fontList)
    lines.push(`${FONT_COPYRIGHTS[font.pkg].name}: ${FONT_COPYRIGHTS[font.pkg].copyright}`, '');
  lines.push('```text', oflText(fontList[0].pkg), '```', '');
  for (const name of packages) {
    lines.push(`### ${name}`, '', '```text', licenseText(name), '```', '');
  }
  return lines.join('\n');
}

const text = render();
if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== text) {
    console.error('THIRD_PARTY_NOTICES.md is out of date: run `node scripts/build_third_party_notices.mjs`.');
    process.exit(1);
  }
  console.log('THIRD_PARTY_NOTICES.md is up to date.');
} else {
  writeFileSync(OUT, text);
  console.log(`Wrote THIRD_PARTY_NOTICES.md (${fonts().length} fonts, ${bundledPackages().length} packages).`);
}
